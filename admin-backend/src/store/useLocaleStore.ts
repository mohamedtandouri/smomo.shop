interface LocaleState {
  language: LanguageCode
  direction: Direction
  _hasHydrated: boolean
  setHasHydrated: (state: boolean) => void
  setLanguage: (lang: LanguageCode) => void
  t: (key: string, fallback?: string) => string
}

export const useLocaleStore = create<LocaleState>()(
  persist(
    (set, get) => ({
      language: "ar",
      direction: "rtl",
      _hasHydrated: false,
      setHasHydrated: (state: boolean) => set({ _hasHydrated: state }),
      setLanguage: (lang: LanguageCode) => {
        const option = SUPPORTED_LANGUAGES.find((l) => l.code === lang)
        const direction: Direction = option ? option.direction : "rtl"

        if (typeof document !== "undefined") {
          document.documentElement.lang = lang
          document.documentElement.dir = direction
          document.cookie = `NEXT_LOCALE=${lang}; path=/; max-age=31536000; SameSite=Lax`
        }

        set({ language: lang, direction })
      },
      t: (key: string, fallback?: string) => {
        const currentLang = get().language || "ar"
        const dictionary = translations[currentLang] || translations.ar || translations.en
        return dictionary[key] || translations.ar?.[key] || translations.en?.[key] || fallback || key
      },
    }),
    {
      name: "smomo-locale-storage",
      skipHydration: true,
      onRehydrateStorage: () => (state) => {
        state?.setHasHydrated(true)
      },
    }
  )
)

// دالة مساعدة لترجمة عناصر القوائم القياسية تلقائياً حسب اللغة المختارة
export function translateMenuLabel(
  label: string,
  t: (key: string, fallback?: string) => string
): string {
  const normalized = label.trim().toLowerCase()
  const keyMap: Record<string, string> = {
    home: "menu_label.home",
    "all products": "menu_label.all_products",
    products: "store.products",
    categories: "menu_label.categories",
    "about us": "menu_label.about_us",
    "contact us": "menu_label.contact_us",
    "shipping policy": "menu_label.shipping_policy",
    "shipping & returns": "menu_label.shipping_policy",
    "privacy policy": "menu_label.privacy_policy",
    faq: "menu_label.faq",
    faqs: "menu_label.faq",
  }
  const key = keyMap[normalized]
  return key ? t(key, label) : label
}

